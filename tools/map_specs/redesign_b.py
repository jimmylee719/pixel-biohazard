LEGACY = open(os.path.join(HERE, "..", "tests", "legacy_areas.gd"), encoding="utf-8").read()
AREAS = {}
SOLID = set("#CH=~")
ROOM_EDGE = set("#=+Dp")
DIRS = {"N": (0, -1), "S": (0, 1), "W": (-1, 0), "E": (1, 0)}


def _legacy_block(area_id):
    start = LEGACY.index('\n\t"%s": {\n' % area_id)
    return LEGACY[start:LEGACY.index("\n\t},\n", start)]


def _legacy_field(area_id, name):
    import area_patch
    block = _legacy_block(area_id)
    sp = area_patch.field_span(block, name)
    return block[sp[1]:sp[2]] if sp else ""


def _flood_rect(rows, x, y):
    """從 (x, y) 開始、被牆／窗／門圍住的那一間的外框（Rect2i 的四個數字）。"""
    seen, stack = {(x, y)}, [(x, y)]
    while stack:
        cx, cy = stack.pop()
        for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            n = (cx + dx, cy + dy)
            if 0 <= n[1] < len(rows) and 0 <= n[0] < len(rows[0]) and n not in seen and rows[n[1]][n[0]] not in ROOM_EDGE:
                seen.add(n)
                stack.append(n)
    xs, ys = [c[0] for c in seen], [c[1] for c in seen]
    return (min(xs), min(ys), max(xs) - min(xs) + 1, max(ys) - min(ys) + 1)


def area(area_id, art, marks, sets=(), sets_first=(), indoor=(), hazards=(), fields=None, zone=None):
    """把畫好的地圖變成 area_patch 的規格。
    marks：{記號: (實際符號, [(種類, 值), ...])}，種類：
        name 任務物件名稱／hidden 旗標／loot [物品, 數量]／gear 裝備／safe（值不用，文字沿用舊資料）／stairs 目標區域／
        prop 圖檔（這一塊家具的左上角；記號可以重複）／entry 入口名稱／door (門 id, 目標區域, 進來時往哪邊站 N/S/W/E)／
        set 房間種類（這一間的範圍自動算）／indoor 同 set，再加進 indoor_rects（戶外區域裡的建築）／hazard 危害種類（這一間）
    sets、indoor、hazards：另外手寫的範圍 [((x, y, w, h), 值)]。sets 的順序 = sets_first、自動算的房間（照 marks 的順序）、sets（先符合的優先）。
    zone：溫度區域的名稱（整張地圖一個區域，heated 沿用舊資料）。
    """
    rows = [r for r in art.split("\n") if r.strip() != ""]
    w = len(rows[0])
    for y, r in enumerate(rows):
        assert len(r) == w, "%s 第 %d 列長度 %d（應該 %d）：%s" % (area_id, y, len(r), w, r)
    grid = [list(r) for r in rows]
    found = {}
    for y in range(len(grid)):
        for x in range(w):
            ch = grid[y][x]
            if ch in marks:
                found.setdefault(ch, []).append((x, y))
                grid[y][x] = marks[ch][0]
            else:
                assert ord(ch) < 128, "%s (%d,%d) 有沒定義的記號 %s" % (area_id, x, y, ch)
    for mk in marks:
        assert mk in found, "%s：記號 %s 沒有畫在地圖上" % (area_id, mk)
    rows = ["".join(r) for r in grid]
    out = {k: {} for k in ("names", "hidden", "loot", "gear", "safes", "stairs", "props", "entries", "doors")}
    auto_sets, indoor_rects, hazard_rects = [], [], [(r, k) for r, k in hazards]
    old_safes = re.findall(r'"\d+,\d+": (\{.*?\})(?:, "\d+,\d+"|$)', _legacy_field(area_id, "safes").strip()[1:-1])
    for mk, (real, metas) in marks.items():
        for kind, value in metas:
            if kind != "prop":
                assert len(found[mk]) == 1, "%s：記號 %s 畫了 %d 次" % (area_id, mk, len(found[mk]))
            x, y = found[mk][0]
            key = "%d,%d" % (x, y)
            if kind == "name":
                out["names"][key] = '"%s"' % value
            elif kind == "hidden":
                out["hidden"][key] = '"%s"' % value
            elif kind == "loot":
                out["loot"][key] = '["%s", %d]' % tuple(value)
            elif kind == "gear":
                out["gear"][key] = '"%s"' % value
            elif kind == "stairs":
                out["stairs"][key] = '"%s"' % value
            elif kind == "safe":
                out["safes"][key] = old_safes[len(out["safes"])]
            elif kind == "prop":
                for px, py in found[mk]:
                    out["props"]["%d,%d" % (px, py)] = '"set/%s"' % value
            elif kind == "entry":
                out["entries"][value] = "Vector2i(%d, %d)" % (x, y)
            elif kind == "door":
                did, to, side = value
                out["doors"][did] = '{"cell": Vector2i(%d, %d), "to": "%s", "spawn_dir": Vector2i(%d, %d)}' % ((x, y, to) + DIRS[side])
            elif kind in ("set", "indoor"):
                rect = _flood_rect(rows, x, y)
                auto_sets.append((rect, value))
                if kind == "indoor":
                    indoor_rects.append(rect)
            elif kind == "hazard":
                hazard_rects.append((_flood_rect(rows, x, y), value))
            else:
                raise ValueError(kind)
    indoor_rects += [r for r in indoor]
    all_sets = list(sets_first) + auto_sets + list(sets)

    def dict_src(d, multiline=False):
        if not d:
            return "{}"
        if multiline:
            return "{\n" + "".join('\t\t\t"%s": %s,\n' % (k, v) for k, v in d.items()) + "\t\t}"
        return "{" + ", ".join('"%s": %s' % (k, v) for k, v in d.items()) + "}"

    def rect_src(r):
        return "Rect2i(%d, %d, %d, %d)" % tuple(r)

    f = {}
    for k in ("names", "hidden", "loot", "gear", "safes", "stairs", "props"):
        if out[k] or _legacy_field(area_id, k):
            f[k] = dict_src(out[k])
    f["doors"] = dict_src(out["doors"], True)
    if out["entries"] or _legacy_field(area_id, "entries"):
        f["entries"] = dict_src(out["entries"])
    if all_sets:
        f["sets"] = "[\n" + "".join('\t\t\t{"rect": %s, "set": "%s"},\n' % (rect_src(r), s) for r, s in all_sets) + "\t\t]"
    if indoor_rects or _legacy_field(area_id, "indoor_rects"):
        f["indoor_rects"] = "[" + ", ".join(rect_src(r) for r in indoor_rects) + "]"
    if hazard_rects or _legacy_field(area_id, "hazards"):
        f["hazards"] = "[" + ", ".join('{"rect": %s, "kind": "%s"}' % (rect_src(r), k) for r, k in hazard_rects) + "]"
    if zone:
        heated = "true" if '"heated": true' in _legacy_field(area_id, "zones") else "false"
        f["zones"] = '{\n\t\t\t"%s": {"rect": Rect2i(0, 0, %d, %d), "heated": %s},\n\t\t}' % (zone, w, len(rows), heated)
    # 鏡頭傾斜、固定機位已經全部拿掉（使用者不喜歡）
    f["tilt"] = None
    f["camera_zones"] = None
    f.update(fields or {})
    _check(area_id, rows, out)
    AREAS[area_id] = {"map": rows, "allow_diff": True, "fields": f}


def _check(area_id, rows, out):
    h, w = len(rows), len(rows[0])
    # 巡邏點
    for route in re.findall(r'"route": "(\w+)"', _legacy_field(area_id, "enemies")):
        for ch in route:
            n = sum(r.count(ch) for r in rows)
            assert n == 1, "%s：巡邏點 %s 有 %d 個" % (area_id, ch, n)
    # 任務物件、裝備、樓梯：和舊資料一樣多
    for k in ("names", "gear", "stairs"):
        old = sorted(re.findall(r'"\d+,\d+": ("[^"]*")', _legacy_field(area_id, k)))
        assert old == sorted(out[k].values()), "%s.%s 和舊資料不一樣：%s / %s" % (area_id, k, sorted(out[k].values()), old)
    old_doors = sorted(re.findall(r'"(\w+)": \{[^{}\n]*"cell"', _legacy_field(area_id, "doors")))
    assert old_doors == sorted(out["doors"]), "%s 的門：%s / %s" % (area_id, sorted(out["doors"]), old_doors)
    for k in ("names", "hidden", "loot", "gear", "safes", "stairs"):
        for key in out[k]:
            x, y = map(int, key.split(","))
            assert rows[y][x] not in "#.C", "%s.%s %s 指到 %s" % (area_id, k, key, rows[y][x])
    n_d = sum(r.count("D") for r in rows)
    assert n_d == len(out["doors"]), "%s：D 有 %d 個、門有 %d 扇" % (area_id, n_d, len(out["doors"]))
    # 連通
    passable = {(x, y) for y in range(h) for x in range(w) if rows[y][x] not in SOLID}
    start = sorted(passable)[0]
    seen, stack = {start}, [start]
    while stack:
        x, y = stack.pop()
        for n in ((x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)):
            if n in passable and n not in seen:
                seen.add(n)
                stack.append(n)
    rest = passable - seen
    assert not rest, "%s：有 %d 格走不到（例如 %s）" % (area_id, len(rest), sorted(rest)[:4])


